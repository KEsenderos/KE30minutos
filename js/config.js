// エラーの種類。code は FORMAT TOO_BIG DUP LIB_FULL TOO_LONG DECODE DB QUOTA AUDIO REC_FULL など。画面の文言は TEXT['ERR_' + code]
class KeError extends Error {
  constructor(code, detail) {
    super(code);
    this.name = 'KeError';
    this.code = code;
    this.detail = detail || {};
  }
}
